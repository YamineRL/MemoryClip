#!/usr/bin/env python3
"""Build docs/changelog.html from Scripts/release-notes/*.md, newest first.

    python3 Scripts/make_changelog.py

Run it after writing a new release-notes file. Each release is dated by the
commit that added its notes; a file not committed yet shows no date. The notes
use a small subset of Markdown — ## / ### headings, "- " bullets that wrap onto
indented lines, **bold**, *italic* and `code` — and that is all this converts.
"""
import html
import re
import subprocess
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
NOTES = ROOT / "Scripts" / "release-notes"
OUT = ROOT / "docs" / "changelog.html"


def version_key(path):
    return tuple(int(p) for p in path.stem.split("."))


def added_on(path):
    out = subprocess.run(
        ["git", "log", "--diff-filter=A", "--format=%ad", "--date=short", "--", str(path)],
        cwd=ROOT, capture_output=True, text=True,
    ).stdout.split()
    if not out:
        return ""
    d = date.fromisoformat(out[-1])
    return f"{d.day} {d:%B %Y}"


def inline(text):
    text = html.escape(text, quote=False)
    text = re.sub(r"`([^`]+)`", r"<code>\1</code>", text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"(?<![\w*])\*(?!\s)(.+?)(?<!\s)\*(?![\w*])", r"<em>\1</em>", text)
    return text


def convert(md):
    """Markdown subset → HTML. Headings become h3 inside a release."""
    blocks, items, para = [], None, None

    def flush():
        nonlocal items, para
        if items is not None:
            blocks.append("<ul>\n" + "\n".join(f"<li>{inline(i)}</li>" for i in items) + "\n</ul>")
        if para is not None:
            blocks.append(f"<p>{inline(para)}</p>")
        items = para = None

    for line in md.splitlines():
        if not line.strip():
            flush()
        elif line.startswith("#"):
            flush()
            blocks.append(f"<h3>{inline(line.lstrip('#').strip())}</h3>")
        elif line.startswith("- "):
            if para is not None:
                flush()
            items = (items or []) + [line[2:].strip()]
        elif items is not None:
            items[-1] += " " + line.strip()
        else:
            para = (para + " " if para else "") + line.strip()
    flush()
    return "\n".join(blocks)


