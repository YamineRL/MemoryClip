RELEASE = """    <article class="release" id="v{v}">
      <div class="when"><b><a href="https://github.com/YamineRL/MemoryClip/releases/tag/v{v}">{v}</a></b><span>{when}</span></div>
      <div>
{body}
      </div>
    </article>"""


def main():
    files = sorted(NOTES.glob("*.md"), key=version_key, reverse=True)
    releases = "\n".join(
        RELEASE.format(v=f.stem, when=added_on(f), body=convert(f.read_text()))
        for f in files
    )
    OUT.write_text(PAGE.replace("{releases}", releases))
    print(f"{OUT.relative_to(ROOT)}: {len(files)} releases, {files[0].stem} … {files[-1].stem}")


if __name__ == "__main__":
    main()
